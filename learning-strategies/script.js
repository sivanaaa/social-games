const cardList = document.getElementById('cardList');
const filters = document.getElementById('filters');
let openId = null;

function renderCards(filter) {
  const items = filter === 'all' ? STRATEGIES : STRATEGIES.filter(s => s.category === filter);
  cardList.innerHTML = items.map(cardHTML).join('');

  cardList.querySelectorAll('.strategy-card').forEach(card => {
    card.querySelector('.card-head').addEventListener('click', () => {
      const id = card.dataset.id;
      openId = openId === id ? null : id;
      renderCards(currentFilter);
    });
  });
}

function cardHTML(s) {
  const isOpen = openId === s.id;
  return `
    <article class="strategy-card ${isOpen ? 'open' : ''}" data-id="${s.id}">
      <button class="card-head" aria-expanded="${isOpen}">
        <span class="card-tag">${s.category}</span>
        <span class="card-name">${s.name}</span>
        <span class="card-oneliner">${s.oneLiner}</span>
        <span class="card-toggle">${isOpen ? '−' : '+'}</span>
      </button>
      ${isOpen ? `
      <div class="card-body">
        <section class="why">
          <h3>למה זה עובד</h3>
          <p>${s.why}</p>
        </section>
        <section class="howto">
          <h3>איך מיישמים בכיתה</h3>
          <ul>${s.howTo.map(t => `<li>${t}</li>`).join('')}</ul>
        </section>
        <section class="tool">
          <h3>כלי מעשי: ${s.tool.title}</h3>
          <ol>${s.tool.steps.map(t => `<li>${t}</li>`).join('')}</ol>
        </section>
      </div>` : ''}
    </article>
  `;
}

let currentFilter = 'all';

filters.querySelectorAll('.filter-chip').forEach(chip => {
  chip.addEventListener('click', () => {
    filters.querySelectorAll('.filter-chip').forEach(c => c.classList.remove('active'));
    chip.classList.add('active');
    currentFilter = chip.dataset.filter;
    openId = null;
    renderCards(currentFilter);
  });
});

renderCards(currentFilter);
